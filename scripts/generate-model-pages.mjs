const EXAMPLE_ROLE = { image: ['first_frame', 'reference_image'], reference: ['reference_image', 'reference_video'] }
const EXAMPLE_PROMPT = { generate_image: 'A watercolor fox reading a map in a pine forest', generate_video: 'A paper boat drifting down a rainy city street, slow tracking shot', generate_music: 'Warm indie folk, acoustic guitar and soft vocals, a quiet morning walk', generate_sound_effect: 'A heavy wooden door creaking open in an empty stone hall', generate_speech: 'Good morning. The city is still waking up.' }
// Vocal music with default parameters needs lyrics.
const EXAMPLE_LYRICS = { generate_music: '[Verse]\nMorning light on an empty street\n[Chorus]\nWalk with me, slow and sweet' }
// Music models that take no custom lyrics: their vocal example asks the model to write them.
const AUTO_LYRICS_MODELS = new Set(['elevenlabs/music-v2', 'elevenlabs/music-v2.5'])

const code = value => `\`${typeof value === 'string' ? value : JSON.stringify(value)}\``
const cell = text => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ')

/** `openai/gpt-image-2.5-flare` → { creator: 'openai', slug: 'gpt-image-2-5-flare' }. */
export function pagePath(id) {
  const [creator, name] = id.split('/')
  return { creator, slug: name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') }
}

/** Merges operations that the contract splits per input mode into one view per operation kind. */
function operationViews(model) {
  const views = new Map()
  for (const op of model.operations) {
    const view = views.get(op.operation) ?? { operation: op.operation, modes: [], constraints: {}, params: new Map() }
    for (const mode of op.input_modes) {
      if (view.modes.includes(mode)) continue
      view.modes.push(mode)
      view.constraints[mode] = op.input_constraints[mode] ?? {}
      for (const param of op.parameters) {
        const slot = view.params.get(param.name) ?? new Map()
        const key = JSON.stringify({ ...param, locales: undefined })
        const variant = slot.get(key) ?? { param, modes: [] }
        variant.modes.push(mode)
        slot.set(key, variant)
        view.params.set(param.name, slot)
      }
    }
    views.set(op.operation, view)
  }
  return [...views.values()]
}

function roleCell(constraint, t) {
  const lines = []
  if (constraint.reference_counts_by_role) {
    for (const [role, count] of Object.entries(constraint.reference_counts_by_role)) {
      // A role capped at 0 next to subject_references is only accepted inside a subject (e.g. a subject's voice).
      const amount = count.maximum === 0 && constraint.subject_references ? t.subjectOnly : count.minimum === count.maximum ? count.maximum : t.range(count.minimum, count.maximum)
      lines.push(`\`${role}\` ${amount}`)
    }
  } else if (constraint.allowed_reference_roles?.length) {
    lines.push(constraint.allowed_reference_roles.map(role => `\`${role}\``).join(t.sep))
  }
  if (constraint.required_any_reference_roles?.length) {
    lines.push(t.atLeastOne(constraint.required_any_reference_roles.map(role => `\`${role}\``).join(t.sep)))
  }
  for (const [role, seconds] of Object.entries(constraint.max_duration_by_reference_role ?? {})) lines.push(t.maxDuration(role, seconds))
  return lines.join('<br />') || t.none
}

/** Subject grouping rules from input_constraints.<mode>.subject_references. */
function subjectLines(mode, limits, t) {
  const s = t.subjects
  const count = (a, b) => a === b ? `${b}` : t.range(a, b)
  const items = [s.photos(limits.max_subjects, count(limits.min_images_per_subject, limits.max_images_per_subject))]
  if (limits.max_videos_per_subject) items.push(s.videos(limits.max_video_subjects, limits.max_videos_per_subject))
  if (limits.max_audios_per_subject) items.push(s.voices(limits.max_audios_per_subject, limits.max_audio_only_subjects))
  items.push(limits.mixed ? s.mixed : s.exclusive)
  const values = list => list.map(code).join(t.sep)
  const overrides = []
  if (limits.resolutions?.length) overrides.push(`${s.resolution}${t.colon}${values(limits.resolutions)}`)
  if (limits.aspect_ratios?.length) overrides.push(`${s.aspectRatio}${t.colon}${values(limits.aspect_ratios)}${limits.default_aspect_ratio ? s.defaultValue(code(limits.default_aspect_ratio)) : ''}`)
  if (limits.allowed_durations?.length) overrides.push(`${s.duration}${t.colon}${values(limits.allowed_durations.map(d => s.seconds(d)))}`)
  else if (limits.max_duration_seconds) overrides.push(`${s.duration}${t.colon}${s.seconds(t.range(limits.min_duration_seconds, limits.max_duration_seconds))}`)
  if (limits.allowed_audios?.length) overrides.push(`${s.audio}${t.colon}${values(limits.allowed_audios)}`)
  const lines = ['', `### ${s.title(mode)}`, '', s.intro, '', ...items.map(item => `- ${item}`)]
  if (overrides.length) lines.push('', s.overrides, '', ...overrides.map(item => `- ${item}`))
  return lines
}

function valuesCell(param, t) {
  const numeric = param.values?.length ? param.values.map(code).join(t.sep)
    : param.minimum !== undefined && param.maximum !== undefined ? t.range(code(param.minimum), code(param.maximum))
    : param.type
  return [numeric, ...(param.string_values ?? []).map(code)].join(t.sep)
}

function exampleRequest(model, view, mode) {
  const parameters = {}
  for (const slot of view.params.values()) {
    for (const { param, modes } of slot.values()) {
      if (modes.includes(mode) && param.default !== undefined) parameters[param.name] = param.default
    }
  }
  const input = { type: mode, prompt: EXAMPLE_PROMPT[view.operation] }
  if (AUTO_LYRICS_MODELS.has(model.id)) parameters.lyrics_optimizer = true
  else if (EXAMPLE_LYRICS[view.operation]) input.lyrics = EXAMPLE_LYRICS[view.operation]
  const constraint = view.constraints[mode]
  if (constraint.max_references) {
    const roles = constraint.allowed_reference_roles ?? []
    const counted = Object.entries(constraint.reference_counts_by_role ?? {}).filter(([, count]) => count.minimum > 0).map(([role]) => role)
    const required = [...new Set([...(constraint.required_reference_roles ?? []), ...counted])]
    const picked = required.length ? required : [(EXAMPLE_ROLE[mode] ?? []).find(role => roles.includes(role)) ?? roles[0]]
    input.references = picked.map(role => ({ role, file_id: 'file_...' }))
  }
  return { model: model.id, input, parameters }
}

/** Ends a contract description with sentence punctuation so it reads after the lead-in. */
const sentence = (text, lang) => /[.。!！?？]$/.test(text) ? text : `${text}${lang === 'zh' ? '。' : '.'}`

export function renderPage(model, lang, notesFile) {
  const t = TEXT[lang]
  const locale = LOCALES[lang]
  const text = model.locales[locale.contract] ?? model.locales.en
  const views = operationViews(model)
  const aliases = model.aliases ?? []
  const lines = [
    '---',
    `title: ${JSON.stringify(text.label)}`,
    `description: ${JSON.stringify(text.description)}`,
    'seo:',
    `  title: ${JSON.stringify(t.seoTitle(text.label))}`,
    `  description: ${JSON.stringify(t.seoDescription(text.label, model.id, sentence(text.description, lang)))}`,
    '---',
    '',
    `{/* ${t.generated} ${notesFile ? notesFile.replace(/^\//, 'docs/') : `docs${locale.notesRoot}/`} */}`,
    '',
    `| ${t.modelId} | ${aliases.length > 1 ? t.aliases : t.alias} | ${t.endpoint} |`,
    '| --- | --- | --- |',
    `| \`${model.id}\` | ${aliases.map(code).join(t.sep) || t.none} | ${views.map(view => t.operations[view.operation]).join(t.sep)} |`,
    '',
  ]
  for (const view of views) {
    lines.push(`## ${t.inputModes}`, '', `| ${t.mode} | ${t.references} | ${t.roles} |`, '| --- | --- | --- |')
    for (const mode of view.modes) {
      const constraint = view.constraints[mode]
      const count = constraint.max_references ? (constraint.min_references === constraint.max_references ? `${constraint.max_references}` : t.range(constraint.min_references, constraint.max_references)) : t.none
      lines.push(`| \`${mode}\` ${t.modeNames[mode] ?? ''} | ${count} | ${roleCell(constraint, t)} |`)
    }
    const promptOptionalModes = view.modes.filter(mode => view.constraints[mode].prompt_optional === true)
    if (promptOptionalModes.length) lines.push('', `${t.optionalPrompt} ${promptOptionalModes.map(code).join(t.sep)}`)
    for (const mode of view.modes) {
      if (view.constraints[mode].subject_references) lines.push(...subjectLines(mode, view.constraints[mode].subject_references, t))
    }
    lines.push('', `## ${t.parameters}`, '', `| ${t.param} | ${t.desc} | ${t.values} | ${t.def} | ${t.req} |`, '| --- | --- | --- | --- | --- |')
    for (const [name, slot] of view.params) {
      for (const { param, modes } of slot.values()) {
        const label = param.locales[locale.contract] ?? param.locales.en
        const scoped = modes.length < view.modes.length ? ` ${t.onlyIn(modes.map(code).join(t.sep))}` : ''
        lines.push(`| \`${name}\` | ${cell(`${label.label}${t.colon}${label.description}${scoped}`)} | ${cell(valuesCell(param, t))} | ${param.default === undefined ? t.notSet : code(param.default)} | ${param.required ? t.yes : t.no} |`)
      }
    }
    lines.push('', `## ${t.examples}`, '')
    for (const mode of view.modes) {
      lines.push(t.example(mode), '', '```json', JSON.stringify(exampleRequest(model, view, mode), null, 2), '```', '')
    }
  }
  lines.push(t.contract(model.id), '')
  if (notesFile) lines.push(`<include>${notesFile}</include>`, '')
  return lines.join('\n')
}

// Monochrome creator mark (lobehub/icons, MIT; ElevenLabs and Suno from simple-icons, CC0; Prodia, Pruna and Topaz drawn to match), inlined so
// it follows the sidebar text color in both themes. Same marks as yir-web.
function creatorIcon(creator) {
  const paths = creatorMarks[creator]
  if (!paths) throw new Error(`Add a sidebar mark for creator ${creator}`)
  return `<svg viewBox="0 0 24 24" width="100%" height="100%" fill="currentColor" fill-rule="evenodd" xmlns="http://www.w3.org/2000/svg">${paths.map((d) => `<path d="${d}"/>`).join('')}</svg>`
}

function renderMeta(creator, slugs) {
  return `import { defineMeta } from "blume";\n\n// Generated by scripts/generate-model-pages.mjs.\nexport default defineMeta({\n  title: ${JSON.stringify(CREATORS[creator])},\n  icon: ${JSON.stringify(creatorIcon(creator))},\n  display: "group",\n  collapsed: true,\n  pages: ${JSON.stringify(slugs)},\n});\n`
}

function renderCatalog(models, lang) {
  const t = TEXT[lang]
  const locale = LOCALES[lang]
  const lines = [`{/* ${t.generated.split(';')[0]} */}`, '', `| ${t.model} | ID | ${t.type} |`, '| --- | --- | --- |']
  for (const model of models) {
    const { creator, slug } = pagePath(model.id)
    const label = (model.locales[locale.contract] ?? model.locales.en).label
    const types = [...new Set(model.operations.map(op => t.types[op.operation]))].join(t.sep)
    lines.push(`| [${label}](${locale.docs}/models/${creator}/${slug}) | \`${model.id}\` | ${types} |`)
  }
  return lines.join('\n') + '\n'
}

/** Every generated file as { relativePath: content }, plus the notes files the pages expect. */
export async function buildPages() {
  const { models } = JSON.parse(await readFile(contractsPath, 'utf8'))
  const sorted = [...models].sort((a, b) => a.id.localeCompare(b.id))
  const files = {}
  const notesUsed = new Set()
  for (const [lang, locale] of Object.entries(LOCALES)) {
    const byCreator = new Map()
    for (const model of sorted) {
      const { creator, slug } = pagePath(model.id)
      if (!CREATORS[creator]) throw new Error(`Add a sidebar title for creator ${creator}`)
      byCreator.set(creator, [...(byCreator.get(creator) ?? []), slug])
      const notesRel = SHARED_NOTES[model.id] ?? `${creator}/${slug}`
      const notesPath = `${locale.dir}/_notes/${notesRel}.mdx`
      const exists = await readFile(path.join(root, notesPath), 'utf8').then(() => true, () => false)
      if (exists) notesUsed.add(notesPath)
      files[`${locale.dir}/${creator}/${slug}.mdx`] = renderPage(model, lang, exists ? `${locale.notesRoot}/${notesRel}.mdx` : null)
    }
    for (const [creator, slugs] of byCreator) files[`${locale.dir}/${creator}/meta.ts`] = renderMeta(creator, slugs)
    files[`${locale.dir}/_catalog.mdx`] = renderCatalog(sorted, lang)
  }
  return { files, notesUsed }
}

/** Generated files currently on disk: creator folders and the catalog snippet. */
export async function existingGeneratedFiles() {
  const out = []
  for (const locale of Object.values(LOCALES)) {
    for (const creator of Object.keys(CREATORS)) {
      const dir = path.join(root, locale.dir, creator)
      for (const name of await readdir(dir).catch(() => [])) out.push(`${locale.dir}/${creator}/${name}`)
    }
    out.push(`${locale.dir}/_catalog.mdx`)
  }
  return out
}

/** Notes files that no generated page includes. */
export async function orphanNotes(notesUsed) {
  const orphans = []
  for (const locale of Object.values(LOCALES)) {
    const base = path.join(root, locale.dir, '_notes')
    for (const creator of await readdir(base).catch(() => [])) {
      for (const name of await readdir(path.join(base, creator)).catch(() => [])) {
        const rel = `${locale.dir}/_notes/${creator}/${name}`
        if (!notesUsed.has(rel)) orphans.push(rel)
      }
    }
  }
  return orphans
}

async function main(check) {
  const { files, notesUsed } = await buildPages()
  const orphans = await orphanNotes(notesUsed)
  if (orphans.length) throw new Error(`Notes without a model page:\n${orphans.join('\n')}`)
  const stale = []
  for (const [rel, content] of Object.entries(files)) {
    const current = await readFile(path.join(root, rel), 'utf8').catch(() => null)
    if (current?.replace(/\r\n/g, '\n') !== content) stale.push(rel)
  }
  const extra = (await existingGeneratedFiles()).filter(rel => !(rel in files))
  if (check) {
    if (stale.length || extra.length) throw new Error(`Model pages are stale; run pnpm generate:models\n${[...stale, ...extra].join('\n')}`)
    console.log('Model pages are up to date')
    return
  }
  for (const rel of extra) await rm(path.join(root, rel), { force: true })
  for (const rel of stale) {
    await mkdir(path.dirname(path.join(root, rel)), { recursive: true })
    await writeFile(path.join(root, rel), files[rel], 'utf8')
  }
  console.log(`Wrote ${stale.length} and removed ${extra.length} model page files`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main(process.argv.includes('--check'))
}
